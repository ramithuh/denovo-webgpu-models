#!/usr/bin/env python3
"""Export pinned residue ordering and small canonical reference library."""
import json
import numpy as np
from checkpoint import ROOT
from rfd3.constants import association_schemes_stripped
from atomworks.ml.encoding_definitions import AF3SequenceEncoding
from atomworks.io.utils.ccd import get_ccd_component_from_biotite
s=AF3SequenceEncoding()
names=['ALA','ARG','ASN','ASP','CYS','GLN','GLU','GLY','HIS','ILE','LEU','LYS','MET','PHE','PRO','SER','THR','TRP','TYR','VAL','UNK','A','C','G','U','N','DA','DC','DG','DT','DN','MSK']
data={'atom14':association_schemes_stripped['dense'],'restypes':dict(zip(names,s.encode(np.array(names)).tolist())), 'references':{}}
for name in ['A','C','G','U','DA','DC','DG','DT','ZN','ATP']:
    aa=get_ccd_component_from_biotite(name)
    aa=aa[aa.element!='H']
    data['references'][name]={'atoms':[{'name':str(a.atom_name),'element':str(a.element),'charge':int(a.charge),'position':np.nan_to_num(a.coord,nan=0.0,posinf=0.0,neginf=0.0).tolist()} for a in aa], 'bonds':aa.bonds.as_array().tolist()}
(ROOT/'shared/chemistry.js').write_text('// Pinned RFD3 ordering (BSD-3-Clause) and CCD reference data. Generated by tools/export_chemistry.py.\nexport const chemistry='+json.dumps(data,separators=(',',':'))+';\n')
