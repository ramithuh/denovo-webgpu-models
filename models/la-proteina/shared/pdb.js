import constants from './constants.js';
export function structure(result) {
  const length=result.logits.length/20,residueTypes=new Uint8Array(length),atomMask=new Uint8Array(length*37),maskedCoords=new Float32Array(result.coords.length);
  let sequence='';
  for(let i=0;i<length;i++){
    let best=0;for(let j=1;j<20;j++)if(result.logits[i*20+j]>result.logits[i*20+best])best=j;
    residueTypes[i]=best;sequence+=constants.restypes[best];
    for(let a=0;a<37;a++){
      const mask=constants.atom_mask[best][a];atomMask[i*37+a]=mask;
      if(mask)for(let k=0;k<3;k++)maskedCoords[(i*37+a)*3+k]=result.coords[(i*37+a)*3+k];
    }
  }
  const out={...result,length,residueTypes,atomMask,maskedCoords,sequence,pdbTranslationAngstrom:pdbTranslation(result.coords,atomMask)};
  out.pdb=writePDB(out);return out;
}
export function pdbTranslation(coords,atomMask) {
  const lo=[Infinity,Infinity,Infinity],hi=[-Infinity,-Infinity,-Infinity];
  for(let a=0;a<coords.length/3;a++)if(!atomMask||atomMask[a])for(let k=0;k<3;k++){
    const v=coords[a*3+k]*10;if(!Number.isFinite(v))throw Error('Nonfinite PDB coordinate');
    lo[k]=Math.min(lo[k],v);hi[k]=Math.max(hi[k],v);
  }
  return lo.map((v,k)=>v < -999.999 || hi[k]>9999.999 ? -v : 0);
}
export function writePDB({coords,residueTypes,atomMask,pdbTranslationAngstrom}, {chain='A'}={}) {
  if(!/^[A-Za-z0-9]$/.test(chain))throw Error('PDB chain must be one alphanumeric character');
  if(coords.length!==residueTypes.length*111)throw Error('Invalid atom37 coordinates');
  const lines=['REMARK   Generated by La-Proteina LD1 + AE1; coordinates in Angstrom.'];let serial=1;
  const translation=pdbTranslationAngstrom??pdbTranslation(coords,atomMask);
  if(translation.some(x=>x!==0))lines.push('REMARK 900 COORDINATE OFFSET ANGSTROM '+translation.map(x=>x.toFixed(6)).join(' '));
  for(let i=0;i<residueTypes.length;i++){
    const type=residueTypes[i];if(type>19)throw Error('Invalid residue type');
    const res=constants.restype_1to3[constants.restypes[type]];
    for(let a=0;a<37;a++){
      if(!(atomMask?.[i*37+a]??constants.atom_mask[type][a]))continue;
      const atom=constants.atom_types[a], xyz=[];
      for(let k=0;k<3;k++){const v=coords[(i*37+a)*3+k]*10+translation[k],s=v.toFixed(3);if(!Number.isFinite(v)||s.length>8)throw Error('Coordinate extent cannot be represented in PDB');xyz.push(s.padStart(8));}
      const atomName=atom.length<4?' '+atom.padEnd(3):atom;
      lines.push(`ATOM  ${String(serial++).padStart(5)} ${atomName} ${res} ${chain}${String(i+1).padStart(4)}    ${xyz.join('')}  1.00  0.00          ${atom[0].padStart(2)}  `);
    }
  }
  lines.push('TER','END');return lines.join('\n')+'\n';
}
